package com.example.exellio20.models

/**
 * ====================================================================================================
 * МОДЕЛЬ ЕЛЕМЕНТА ВИПАДАЮЧОГО СПИСКУ (SPINNER DATA - EXELLIO 2.0)
 * ====================================================================================================
 *
 * Використовується для відображення списків груп, ставок ПДВ та кодів УКТЗЕД у віджетах [android.widget.Spinner].
 *
 * @property title Відображувана користувачеві назва в меню списку.
 * @property containsValue Внутрішнє значення (код або системний індекс), що зберігається в базі.
 */
data class SpinnerData(
    val title: String,
    val containsValue: String
) {
    /**
     * Стандартний Spinner викликає [toString] для відображення тексту в елементі списку.
     */
    override fun toString(): String {
        return title
    }
}

