package com.example.exelioshop.fragments

import androidx.fragment.app.Fragment

/**
 * =================================================================================================
 * BaseFragment — Базовий абстрактний клас для всіх екранів-фрагментів додатку exelioShop.
 * -------------------------------------------------------------------------------------------------
 * Призначення:
 * Стандартизує інтерфейс для фрагментів, що управляються об'єктом FragmentManager.
 * Вимагає реалізації методу onClickNew() для уніфікованої обробки створення нового запису.
 * =================================================================================================
 */
abstract class BaseFragment : Fragment() {
    /** Обробник створення нового елемента (товару/запису) */
    abstract fun onClickNew()
}