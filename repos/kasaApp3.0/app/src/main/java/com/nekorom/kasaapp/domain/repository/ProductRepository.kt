package com.nekorom.kasaapp.domain.repository

/**
 * Контракт доменного сховища товарів.
 */
interface ProductRepository {
    /**
     * Отримання товарної позиції / списку товарів.
     */
    fun getProduct()

    /**
     * Збереження товарної позиції в сховищі.
     */
    fun saveProduct()
}