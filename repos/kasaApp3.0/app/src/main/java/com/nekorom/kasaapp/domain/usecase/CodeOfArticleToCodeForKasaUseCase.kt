// =================================================================================================
// USE CASE: ГЕНЕРАЦІЯ ВНУТРІШНЬОГО ВАГОВОГО ШТРИХ-КОДУ EAN-13 ДЛЯ РРО DATECS
//
// Архітектурний шар: Domain Layer (Use Case).
// Призначення:
// Формує стандартний 13-значний штрих-код внутрішнього кодування вагового товару (префікс "23"),
// що містить у собі артикул товару та його вагу (цілу і дробову частини).
//
// Структура результуючого штрих-коду EAN-13 (13 знаків):
// [23]       - 2 цифри: префікс внутрішнього вагового товару (ДСТУ / GS1).
// [XXXXX]    - 5 цифр: артикул товару (code), доповнений провідними нулями до 5 символів.
// [YY]       - 2 цифри: ціла частина ваги / кількості (count), доповнена нулями до 2 символів.
// [ZZZ]      - 3 цифри: дробова частина ваги в грамах (fractionalPart), доповнена до 3 символів.
// [C]        - 1 цифра: контрольний розряд (Checksum) за стандартом EAN-13 (modulo 10).
// Разом: 2 + 5 + 2 + 3 + 1 = 13 цифр.
// =================================================================================================

package com.nekorom.kasaapp.domain.usecase

/**
 * Прецедент формування вагового штрих-коду для передачі в касовий апарат.
 */
class CodeOfArticleToCodeForKasaUseCase {

    /**
     * Генерує 13-значний штрих-код EAN-13 на основі коду товару, ваги та грамів.
     *
     * @param code Артикул або внутрішній код товару в РРО (1..5 цифр).
     * @param count Ціла частина ваги (наприклад, "1" для 1.250 кг).
     * @param fractionalPart Дробова частина ваги в грамах (наприклад, "250" для 1.250 кг).
     * @return 13-значний рядок штрих-коду EAN-13 з розрахованим контрольним розрядом.
     */
    fun execute(code : String, count: String, fractionalPart: String): String {
        // Крок 1: Встановлюємо префікс "23" для вагового товару
        var codeToSend = "23"

        // Крок 2: Доповнюємо код товару провідними нулями до фіксованої довжини 5 символів
        var i = 5 - code.length
        while (i > 0) {
            codeToSend += "0"
            i--
        }
        codeToSend += code

        // Крок 3: Доповнюємо цілу частину ваги провідними нулями до 2 символів
        var j = 2 - count.length
        while (j > 0) {
            codeToSend += "0"
            j--
        }
        codeToSend += count

        // Крок 4: Додаємо дробову частину ваги та доповнюємо нулями справа до 3 символів (грами)
        codeToSend += fractionalPart
        var f = 3 - fractionalPart.length
        while (f > 0) {
            codeToSend += "0"
            f--
        }

        // Крок 5: Розрахунок контрольної суми за алгоритмом EAN-13 (Modulo 10)
        // Для парних позицій (0, 2, 4...) вага = 3, для непарних (1, 3, 5...) вага = 1
        var controlSum = 0
        var parity = 0
        for (c in codeToSend) {
            controlSum += if ((parity % 2) == 0) {
                c.toString().toInt() * 3
            } else {
                c.toString().toInt()
            }
            parity++
        }

        // Крок 6: Контрольний розряд = (10 - (сума % 10)) % 10
        controlSum = (10 - (controlSum % 10)) % 10
        codeToSend += controlSum.toString()

        return codeToSend
    }
}