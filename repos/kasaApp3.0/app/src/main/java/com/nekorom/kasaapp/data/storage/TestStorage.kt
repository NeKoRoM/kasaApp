//
// Архітектурний шар: Data Layer (Storage Contract).
// Призначення:
// Абстрагує операції низькорівневого запису та вибірки тестових сутностей TestEntity
// від конкретного рушія сховища (Room Database, SharedPreferences, In-Memory тощо).
// Дозволяє проводити ізольоване модульне тестування бізнес-логіки без прив'язки до SQLite.
// =================================================================================================

package com.nekorom.kasaapp.data.storage

import com.nekorom.kasaapp.data.roomDB.TestEntity

/**
 * Інтерфейс локального сховища тестових записів.
 */
interface TestStorage {
    /**
     * Збереження тестового запису [test] у сховищі.
     * @return true, якщо операція збереження ініційована успішно.
     */
    fun save(test : TestEntity): Boolean

    /**
     * Отримання списку всіх збережених тестових сутностей.
     */
    fun get(): List<TestEntity>
}