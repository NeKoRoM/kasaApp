package com.nekorom.kasaapp.domain.repository

import com.nekorom.kasaapp.domain.models.Test

/**
 * Доменний контракт для операцій з тестовими сутностями.
 */
interface TestRepository {
    /**
     * Отримання списку тестових моделей [Test].
     */
    fun getTest(): List<Test>

    /**
     * Збереження тестової моделі.
     */
    fun saveTest(): Boolean
}