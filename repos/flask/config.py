
"""
Модуль конфігурації Flask-застосунку.
Шлях у системі: flask/config.py

Архітектурна роль:
- Визначає базовий клас `Config` з параметрами середовища виконання.
- DEBUG: Дозволяє режим відлагодження з гарячим перезавантаженням (hot reload) та детальним стектрейсом помилок.
- TESTING: Прапорець тестового режиму для ізольованого прогону тестів (pytest/unittest).
"""

class Config:
    """
    Базова конфігурація Flask.
    Використовується методом app.config.from_object('config.Config').
    """
    DEBUG = True      # Режим відлагодження активний для розробки
    TESTING = False   # Режим тестування вимкнений за замовчуванням