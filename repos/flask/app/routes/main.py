
"""
Головний модуль маршрутизації (Blueprint) Flask-застосунку.
Шлях у системі: flask/app/routes/main.py

Архітектурна роль:
- Оголошує екземпляр Blueprint `main_bp` з назвою 'main'.
- Визначає кореневий маршрут GET '/', що повертає тестову відповідь або статус працездатності мікросервісу.
"""

from flask import Blueprint

# Оголошення блюпринта для модульної структури маршрутів
main_bp = Blueprint('main', __name__)

@main_bp.route('/')
def hello_world():
    """
    Кореневий обробник маршруту '/'.
    Повертає вітальне повідомлення / health check для перевірки з'єднання з клієнтом.
    """
    return 'Hello, World!'