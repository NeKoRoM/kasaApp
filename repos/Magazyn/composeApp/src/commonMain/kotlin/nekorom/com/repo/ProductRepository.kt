import database.Dao
import database.Product
import kotlinx.coroutines.flow.Flow

/**
 * ====================================================================================================
 * ДОМЕННИЙ РЕПОЗИТОРІЙ ТОВАРІВ ТА НОМЕНКЛАТУРИ (PRODUCT REPOSITORY)
 * ====================================================================================================
 *
 * Реалізує патерн Repository у багатоплатформному модулі `composeApp` (KMP).
 * Служить абстракцією між шаром зберігання даних (Room Database через [Dao])
 * та рівнем користувацького інтерфейсу (Compose Multiplatform).
 *
 * @property productDao Об'єкт доступу до локальної бази даних SQLite.
 */
class ProductRepository(private val productDao: Dao) {

    /**
     * Реактивний потік [Flow], що емітить актуальний список складських позицій [Product].
     * Будь-які зміни в базі даних (оновлення через Google Sheets API або локальне редагування)
     * негайно транслюються в UI-компоненти для автоматичного перемальовування.
     */
    val allProducts: Flow<List<Product>> = productDao.getAllProducts()

    // При розширенні архітектури сюди виноситься бізнес-валідація, локальне оновлення залишків
    // та тригери віддаленої синхронізації без прив'язки до життєвого циклу екрана.
}